/** Ergänzt die Kurzform der Seed-Gegenstände zu vollständigen Item-Objekten. */
function toItem(seed: SeedItem, index: number, total: number): Item {
  const created = new Date(
    Date.UTC(2026, 0, 5, 9, 0, 0) + index * 36 * 3_600_000,
  ).toISOString();
  return {
    categoryData: {},
    statusData: {},
    documents: [],
    linkedItemIds: [],
    ...seed,
    createdAt: created,
    updatedAt: new Date(
      Date.UTC(2026, 0, 5, 9, 0, 0) + (total + index) * 36 * 3_600_000,
    ).toISOString(),
  };
}

export function createSeedData(): InventoryData {
  return {
    items: seedItems.map((seed, index) =>
      toItem(seed, index, seedItems.length),
    ),
    primaryLocations,
    secondaryLocations,
    packingLists,
    packingEntries,
    settings: {
      currencyLabel: "CHF",
      dashboardAttentionStatusFilter: [...ATTENTION_STATUSES],
    },
  };
}
